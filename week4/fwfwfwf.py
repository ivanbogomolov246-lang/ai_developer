
n = 5
summa=0

# n = 5, поэтому range(5) дает i = 0, 1, 2, 3, 4.
for i in range(n):
    # 1-й проход: summa = 0 + 0 = 0
    # 2-й проход: summa = 0 + 1 = 1
    # 3-й проход: summa = 1 + 2 = 3
    # 4-й проход: summa = 3 + 3 = 6
    # 5-й проход: summa = 6 + 4 = 10
    # В каждом проходе к старому summa прибавляется текущее i.
    summa=summa+i

# После цикла summa = 10, поэтому на экран выводится: Сумма чисел равна 10.
print("Сумма чисел равна", summa)



    



